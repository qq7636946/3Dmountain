#!/usr/bin/env node
// Rebuild the checked-in worker: node scripts/build-logo-worker.cjs --install
// Dependencies are pinned and installed under the OS temp directory, never the website.
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const dependencyRoot = process.env.LOGO_WORKER_BUILD_DEPS || path.join(os.tmpdir(), 'codex-logo-worker-build-20261004');
const versions = { esbuild: '0.25.10', three: '0.170.0' };
function installed(name) {
  const file = path.join(dependencyRoot, 'node_modules', name, 'package.json');
  return fs.existsSync(file) && JSON.parse(fs.readFileSync(file, 'utf8')).version === versions[name];
}
(async () => {
  if (!Object.keys(versions).every(installed)) {
    if (!process.argv.includes('--install')) throw new Error('Pinned build dependencies missing. Run: node scripts/build-logo-worker.cjs --install');
    fs.mkdirSync(dependencyRoot, { recursive: true });
    const npmCli = process.env.npm_execpath || path.join(path.dirname(process.execPath), 'node_modules', 'npm', 'bin', 'npm-cli.js');
    if (!fs.existsSync(npmCli)) throw new Error('npm CLI not found. Set npm_execpath to npm-cli.js, then rerun with --install.');
    const install = spawnSync(process.execPath, [npmCli, 'install', '--prefix', dependencyRoot, '--no-audit', '--no-fund', '--save-exact', ...Object.entries(versions).map(([name, version]) => `${name}@${version}`)], { stdio: 'inherit', windowsHide: true });
    if (install.status !== 0) throw new Error('Pinned worker dependency installation failed.');
  }
  const esbuild = require(path.join(dependencyRoot, 'node_modules', 'esbuild'));
  const threeRoot = path.join(dependencyRoot, 'node_modules', 'three');
  const license = fs.readFileSync(path.join(threeRoot, 'LICENSE'), 'utf8').replace(/\*\//g, '* /');
  const result = await esbuild.build({
    entryPoints: [path.join(root, 'water-logo-geometry-worker.js')],
    outfile: path.join(root, 'water-logo-geometry-worker.bundle.js'),
    bundle: true, format: 'iife', platform: 'browser', target: 'es2020', minify: true,
    alias: { 'three/addons': path.join(threeRoot, 'examples', 'jsm'), three: path.join(threeRoot, 'src', 'Three.js') }, legalComments: 'inline', metafile: true,
    banner: { js: `/*! Generated by scripts/build-logo-worker.cjs using esbuild ${versions.esbuild} and Three.js ${versions.three}.\n${license}\n*/` }
  });
  const output = Object.entries(result.metafile.outputs).find(([name]) => name.endsWith('water-logo-geometry-worker.bundle.js'));
  console.log(JSON.stringify({ output: output?.[0], bytes: output?.[1].bytes, versions, dependencyRoot }));
})().catch(error => { console.error(error.message); process.exitCode = 1; });
